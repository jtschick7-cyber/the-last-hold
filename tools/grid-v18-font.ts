export function hexRgb(hex: string): readonly [number, number, number] {
  const clean = hex.replace('#', '');
  return [
    Number.parseInt(clean.slice(0, 2), 16),
    Number.parseInt(clean.slice(2, 4), 16),
    Number.parseInt(clean.slice(4, 6), 16),
  ];
}

export function fillPngRect(
  png: PNG,
  x: number,
  y: number,
  w: number,
  h: number,
  hex: string,
): void {
  const [r, g, b] = hexRgb(hex);
  for (let j = 0; j < h; j++) {
    const py = y + j;
    if (py < 0 || py >= png.height) continue;
    for (let i = 0; i < w; i++) {
      const px = x + i;
      if (px < 0 || px >= png.width) continue;
      const idx = (py * png.width + px) * 4;
      png.data[idx] = r;
      png.data[idx + 1] = g;
      png.data[idx + 2] = b;
      png.data[idx + 3] = 255;
    }
  }
}

export function drawBitmapText(
  png: PNG,
  x: number,
  y: number,
  text: string,
  hex: string,
  scale = 2,
): void {
  let cx = x;
  for (const raw of text.toUpperCase()) {
    const glyph = FONT_5X7[raw] ?? FONT_5X7[' '];
    if (glyph) {
      for (let row = 0; row < 7; row++) {
        const line = glyph[row] ?? '';
        for (let col = 0; col < 5; col++) {
          if (line[col] === '#') {
            fillPngRect(png, cx + col * scale, y + row * scale, scale, scale, hex);
          }
        }
      }
    }
    cx += 6 * scale;
  }
}

export function blitCanvasScaled(
  png: PNG,
  canvas: Canvas,
  ox: number,
  oy: number,
  scale: number,
  height: number = canvas.size,
  width: number = canvas.size,
): void {
  for (let y = 0; y < height; y++) {
    for (let x = 0; x < width; x++) {
      const hex = canvas.get(x, y);
      if (hex !== null) fillPngRect(png, ox + x * scale, oy + y * scale, scale, scale, hex);
    }
  }
}
