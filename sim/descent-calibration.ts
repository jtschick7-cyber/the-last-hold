import { median } from './checks/helpers';
import {
  PROBE_PROFILES,
  type DescentCell,
  type DescentProbe,
  type ProbeProfile,
} from './descent-probe';
import type { RunResult } from './run';

// Plan TD.8b (D564, Q59): the Descent calibration table, written for the owner to read before TD.9
// sets the constants. One row per grid point and roster; every column is over the 5 Monday seeds:
// the win rate pools all their practice runs, the other columns are the median of the seeds' medians
// (with the widest 10th–90th range any seed showed). Reported only: it judges nothing.

const probes = (runs: readonly RunResult[]): { seed: string; probe: DescentProbe }[] =>
  runs.flatMap((r) => (r.vigil?.descent ? [{ seed: r.spec.seed, probe: r.vigil.descent }] : []));

const pct = (x: number): string => `${Math.round(x * 100)}%`;
const row = (cells: readonly string[]): string => `| ${cells.join(' | ')} |`;

const profileName: Record<ProbeProfile, string> = {
  minimal: 'Minimal gate-open',
  'minimal-zeroed': 'Minimal, bonus zeroed',
  maxed: 'Maxed endgame',
  'maxed-zeroed': 'Maxed, bonus zeroed',
  hamlet: 'Hamlet starter party',
};

/** One roster at one grid point, pooled over the seeds. */
export interface Pooled {
  readonly winRate: number;
  readonly stages: number;
  readonly downed: number;
  readonly downedLow: number;
  readonly downedHigh: number;
  readonly unlitLeft: number;
}

export const pool = (cells: readonly DescentCell[]): Pooled => {
  const samples = cells.reduce((n, c) => n + c.samples, 0);
  return {
    winRate: samples === 0 ? 0 : cells.reduce((n, c) => n + c.wins, 0) / samples,
    stages: median(cells.map((c) => c.stagesCleared.median)),
    downed: median(cells.map((c) => c.downed.median)),
    downedLow: Math.min(...cells.map((c) => c.downed.p10)),
    downedHigh: Math.max(...cells.map((c) => c.downed.p90)),
    unlitLeft: median(cells.map((c) => c.unlitLeft.median)),
  };
};

export const calibrationMarkdown = (runs: readonly RunResult[]): string => {
  const all = probes(runs);
  const first = all[0]?.probe;
  if (!first)
    return '# Descent calibration\n\nNo run reached a Rising Vigil stand, so there is nothing to report.\n';
  const out: string[] = [
    '# Descent calibration (TD.8b)',
    '',
    `Generated by \`npm run sim:descent\`: the Vigilant on the ${all.length} Monday seeds, each fighting ${first.samples} practice runs (the preview's own dice) per roster and grid point. Reported only; no constant was changed.`,
    '',
    "Columns: **Win** pools every practice run; **Stages** is the median stages cleared (of 3); **Downed** is the median hunters downed over the whole run, with the widest 10th–90th range any seed showed; **Unlit left** is the median Health left on The Unlit at the end of Stage 3, over runs that reached it (0 when it is beaten). Stages, Downed and Unlit left are medians of the seeds' medians.",
    '',
    "Rosters: *Minimal gate-open* (16 species Studied, none Mastered, no chapters, the run's own roster and relics) and *Maxed endgame* (14 hunters at Master Wright, everything learned) from `sim/descent-roster.ts`; *bonus zeroed* is the same roster with What the Hold Learned and the Delve relics removed; *Hamlet starter party* is a new game's starting hunters.",
    '',
  ];
  first.grid.tiers.forEach((tiers, ti) => {
    first.grid.unlitHealth.forEach((health, hi) => {
      out.push(`### Stage tiers ${tiers.join(', ')} · Unlit base Health ${health}`, '');
      out.push(
        row(['Roster', 'Win', 'Stages', 'Downed', 'Unlit left']),
        row(['---', '---', '---', '---', '---']),
      );
      for (const p of PROBE_PROFILES) {
        const cells = all.flatMap((a) => a.probe.cells[p][ti]?.[hi] ?? []);
        const v = pool(cells);
        out.push(
          row([
            profileName[p],
            pct(v.winRate),
            `${v.stages}`,
            `${v.downed} (${v.downedLow}–${v.downedHigh})`,
            `${v.unlitLeft}`,
          ]),
        );
      }
      out.push('');
    });
  });
  return out.join('\n');
};
