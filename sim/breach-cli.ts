import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { constantAt, num } from '../src/core/balance-access';
import type { BreachVariant } from './breach-probe';
import {
  LEVELS,
  SWEEPS,
  collectStates,
  measure,
  moveEconomyBack,
  sweepCell,
  towersKept,
  type Cell,
  type Level,
  type SeedState,
} from './breach-calibration';

// Plan TB.12 (D583, D589 (6)): `npm run sim:breach` writes the Breach calibration table the owner reads
// before TB.13 sets the constants (Q63). `-- --samples 100 --out file.md --quick` (quick: no sweeps).
// Reported only: it judges nothing and changes no constant. Not part of `npm run check`.
const DEFAULT_OUT = fileURLToPath(
  new URL('../docs/flesh-out/v1.5/breach-calibration.md', import.meta.url),
);
const PROPOSAL = fileURLToPath(
  new URL('../docs/flesh-out/v1.5/breach-proposal.md', import.meta.url),
);

const row = (cells: readonly (string | number)[]): string => `| ${cells.join(' | ')} |`;
const range = (c: Cell): string => `${c.median} (${c.p10}–${c.p90}), mean ${c.mean.toFixed(2)}`;
const pct = (x: number): string => `${(x * 100).toFixed(1)}%`;
const f1 = (x: number): string => (Math.round(x * 10) / 10).toString();
const NAME: Record<BreachVariant, string> = {
  auto: 'Auto-arrange',
  tactician: 'Tactician (Suggest layout)',
  bad: 'Bad layout',
  v5: 'Version 5 rules (today)',
};
const VARIANTS: readonly BreachVariant[] = ['auto', 'tactician', 'bad', 'v5'];
const THREE: readonly BreachVariant[] = ['auto', 'tactician', 'bad'];

const main = async (): Promise<void> => {
  const args = process.argv.slice(2);
  const get = (flag: string): string | undefined => {
    const i = args.indexOf(flag);
    return i >= 0 ? args[i + 1] : undefined;
  };
  const samples = Number(get('--samples') ?? num('laststand.previewSamples'));
  const out = get('--out') ?? DEFAULT_OUT;
  const quick = args.includes('--quick');
  const began = performance.now();
  const seeds: readonly SeedState[] = collectStates();
  const lap = (what: string): void =>
    console.error(`${((performance.now() - began) / 1000).toFixed(0)} s: ${what}`);
  lap(`played ${seeds.length} seeds to the first stand`);

  const md: string[] = [
    '# The Breach: calibration (TB.12)',
    '',
    `Generated by \`npm run sim:breach\`: the Tactician on the ${seeds.length} Monday seeds, taken to its first stand at Bastion, then ${samples} practice stands per setup (the preview's own dice, the same seeds for every layout). Numbers are waves held: median (10th–90th, the widest of the seeds). The Walls and Watchtower levels are set on a copy of the state at three named points. Reported only; no constant was changed. The current \`breach.*\` values are the TB.3 placeholders.`,
    '',
    '- **Level points:** ' +
      LEVELS.map((l) => `${l.name} (Walls ${l.walls}, Watchtower ${l.tower})`).join('; ') +
      '.',
    '- **Bands:** Held from ' +
      `${num('band.heldFrom')} waves, Triumphant from ${num('band.triumphantFrom')}. Relics come at ${(constantAt('relics.waveMilestones').value as readonly number[]).join(', ')} waves.`,
    '',
    "## 1. Every layout beside today's rules (placeholder constants)",
    '',
  ];
  const base = new Map<string, Cell>();
  for (const level of LEVELS)
    for (const v of VARIANTS) base.set(`${level.name}/${v}`, measure(seeds, level, v, samples));
  lap('section 1');
  for (const level of LEVELS) {
    md.push(
      `### ${level.name}: Walls ${level.walls}, Watchtower ${level.tower}`,
      '',
      row([
        'Layout',
        'Waves held',
        'Seeds Held+',
        'Seeds Triumphant',
        'Relics',
        '75% cap binds',
        'Mean wall cut',
        'Mean volley',
        'Counted pieces / towers',
      ]),
      row(['---', '---', '---', '---', '---', '---', '---', '---', '---']),
    );
    for (const v of VARIANTS) {
      const c = base.get(`${level.name}/${v}`) as Cell;
      md.push(
        row([
          NAME[v],
          range(c),
          `${c.held} of ${seeds.length}`,
          `${c.triumphant} of ${seeds.length}`,
          c.relics,
          pct(c.capShare),
          `${f1(c.meanCut)}%`,
          f1(c.meanVolley),
          v === 'v5' ? '–' : `${c.pieces} / ${c.towers}`,
        ]),
      );
    }
    md.push('');
  }

  md.push(
    "## 1b. The same at the Tactician's third stand (higher Threat)",
    '',
    'Rows B and C are judged on the first stand (D589). The third stand shows whether the layout matters more when the waves are stronger.',
    '',
  );
  const later = collectStates(2);
  for (const level of LEVELS) {
    md.push(`### ${level.name}`, '', row(['Layout', 'Waves held']), row(['---', '---']));
    for (const v of VARIANTS) md.push(row([NAME[v], range(measure(later, level, v, samples))]));
    md.push('');
  }
  lap('section 1b');

  md.push('## 2. The low Walls level (fewer wall segments, GDD §5.9.11)', '');
  for (const level of LEVELS) {
    const a = base.get(`${level.name}/auto`) as Cell;
    const v5 = base.get(`${level.name}/v5`) as Cell;
    md.push(
      `- **${level.name} (Walls ${level.walls}):** under today's rules the Walls cut ${f1(v5.meanCut)}% in every lane; with Auto-arrange they cut ${f1(a.meanCut)}% on average over the 8 lanes, from ${a.pieces} counted pieces (walls and towers). Waves held ${a.median} against ${v5.median}.`,
    );
  }
  md.push(
    '',
    'At level 1 the Walls give only four segments (more come at levels 3, 5, 7, 9, 11, 13 and 15), so some lanes are open however the hold is arranged.',
    '',
  );

  md.push(
    '## 3. One tower against three (D582)',
    '',
    'Auto-arrange, then towers lifted to the Tray so only the first N stay placed. Towers unlock at Watchtower levels 1, 8 and 15, so the mid point owns two and the max point three.',
    '',
    row(['Point', 'All owned towers', 'Two kept', 'One kept', 'No tower placed']),
    row(['---', '---', '---', '---', '---']),
  );
  for (const level of LEVELS.filter((l) => l.name !== 'low')) {
    const cells = [3, 2, 1, 0].map((n) =>
      n === 3
        ? (base.get(`${level.name}/auto`) as Cell)
        : measure(seeds, level, 'auto', samples, { post: towersKept(n) }),
    );
    md.push(row([level.name, ...cells.map((c) => `${range(c)}, volley ${f1(c.meanVolley)}`)]));
  }
  md.push('');
  lap('section 3');

  md.push(
    '## 4. Moving an economy building off a front-row tile (D581)',
    '',
    "The Tactician's layout with the economy buildings left where they are, then with every movable one-tile economy building moved to a free tile behind the front rows first.",
    '',
    row(['Point', 'Left where they are', 'Moved back', 'Buildings moved']),
    row(['---', '---', '---', '---']),
  );
  for (const level of LEVELS) {
    const left = base.get(`${level.name}/tactician`) as Cell;
    let moved = 0;
    const back = measure(seeds, level, 'tactician', samples, {
      pre: (s) => {
        moved = Math.max(moved, moveEconomyBack(s));
      },
    });
    md.push(row([level.name, range(left), range(back), moved]));
  }
  md.push('');
  lap('section 4');

  if (!quick) {
    md.push(
      '## 5. The tunables, one at a time',
      '',
      'Each row changes only the named constants from the placeholders. Cells are Auto-arrange / Tactician / Bad layout, mean waves held (over every practice stand; the median is a whole number and hides small moves).',
      '',
    );
    let current = '';
    const baseRow = (level: Level): string =>
      THREE.map((v) => (base.get(`${level.name}/${v}`) as Cell).mean.toFixed(2)).join(' / ');
    for (const sweep of SWEEPS) {
      if (sweep.name !== current) {
        current = sweep.name;
        md.push(
          '',
          `### ${sweep.name}`,
          '',
          row(['Value', ...LEVELS.map((l) => l.name)]),
          row(['---', ...LEVELS.map(() => '---')]),
        );
      }
      const cells = LEVELS.map((level) =>
        THREE.map((v) => sweepCell(seeds, sweep, level, v, samples).mean.toFixed(2)).join(' / '),
      );
      md.push(row([sweep.label, ...cells]));
      lap(`${sweep.name} ${sweep.label}`);
    }
    md.push(
      '',
      `The placeholders give ${LEVELS.map((l) => `${l.name} ${baseRow(l)}`).join('; ')}.`,
    );
  }
  md.push('');
  if (existsSync(PROPOSAL)) md.push(readFileSync(PROPOSAL, 'utf8'));
  writeFileSync(out, md.join('\n'));
  console.log(`Wrote ${out} (${((performance.now() - began) / 1000).toFixed(1)} s)`);
};

void main();
