// Technical design §12.4: docs/credits.md is generated from the asset manifest
// and the palette by tools/gen-credits.ts (and shown in About); a test fails if the committed file is
// out of date.
import { assets, type AssetEntry } from '../content/assets';
import { audio, type AudioEntry } from '../content/audio';
import { fonts } from '../content/fonts';
import { palette } from '../content/palette';

type PackAsset = Extract<AssetEntry, { source: 'pack' }>;

/** The sound packs, in the order their first clip appears in the audio list. */
const soundPacks = (): [string, AudioEntry[]][] => {
  const packs = new Map<string, AudioEntry[]>();
  for (const a of audio) packs.set(a.pack, [...(packs.get(a.pack) ?? []), a]);
  return [...packs.entries()];
};

export const buildCredits = (): string => {
  const packs = new Map<string, PackAsset[]>();
  for (const a of assets) {
    if (a.source !== 'pack') continue;
    packs.set(a.pack, [...(packs.get(a.pack) ?? []), a]);
  }
  const generated = assets.filter((a) => a.source === 'generated').length;
  const placeholders = assets.filter((a) => a.source === 'placeholder').length;
  const lines = [
    '# Credits',
    '',
    '<!-- Generated by tools/gen-credits.ts from src/content/assets.ts, src/content/audio.ts and src/content/palette.ts. Do not edit by hand. -->',
    '',
    'The Last Hold is an original game. Every image, font and sound is CC0 (public domain): either from a CC0 pack or made for the game.',
    '',
    '## Palette',
    '',
    palette
      ? `- **${palette.name}** by ${palette.author}, published for free use: ${palette.source}`
      : '- Not chosen yet (plan T1.28).',
    '',
    '## Art packs (CC0)',
    '',
    ...(packs.size === 0
      ? ['- None yet.']
      : [...packs.entries()].map(([name, list]) => {
          const first = list[0];
          return `- **${name}** by ${first?.credit ?? '?'} (${first?.license ?? '?'}): ${first?.url ?? '?'}. ${list.length} ${list.length === 1 ? 'image' : 'images'}.`;
        })),
    '',
    '## Fonts (CC0)',
    '',
    ...fonts.map((f) => `- **${f.name}** from ${f.pack} by ${f.credit} (${f.license}): ${f.url}`),
    '',
    '## Sound packs (CC0)',
    '',
    ...soundPacks().map(([name, list]) => {
      const first = list[0];
      return `- **${name}** by ${first?.credit ?? '?'} (${first?.license ?? '?'}): ${first?.url ?? '?'}. ${list.length} ${list.length === 1 ? 'sound' : 'sounds'}.`;
    }),
    '',
    '## Made for the game',
    '',
    `- ${generated} generated ${generated === 1 ? 'image' : 'images'} (CC0, The Last Hold).`,
    `- ${placeholders} ${placeholders === 1 ? 'asset' : 'assets'} still shown as placeholder silhouettes (original, CC0).`,
    '',
  ];
  return lines.join('\n');
};
